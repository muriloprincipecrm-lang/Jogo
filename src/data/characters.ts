export function normalizarEstadoPessoa(valor: unknown): EstadoPessoa {
  const normalizados: Record<string, EstadoPessoa> = {
    Vivo: "VIVO",
    VIVO: "VIVO",
    Suspeito: "SUSPEITO",
    SUSPEITO: "SUSPEITO",
    Desaparecido: "DESAPARECIDO",
    DESAPARECIDO: "DESAPARECIDO",
    Ferido: "FERIDO",
    FERIDO: "FERIDO",
    Possuído: "POSSUÍDO",
    "POSSUÍDO": "POSSUÍDO",
  };
  return typeof valor === "string" && valor in normalizados
    ? normalizados[valor]
    : ("VIVO" satisfies EstadoPessoa);
}
